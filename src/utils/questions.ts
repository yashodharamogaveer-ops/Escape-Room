export function getRandomQuestion(excludeId?: number): AptitudeQuestion {
  const pool = excludeId ? APTITUDE_QUESTIONS.filter(q => q.id !== excludeId) : APTITUDE_QUESTIONS;
  const index = Math.floor(Math.random() * pool.length);
  return pool[index];
}
